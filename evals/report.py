"""Render the Markdown evaluation report. Deterministic: same run file -> same bytes."""
from __future__ import annotations

from statistics import mean
from typing import Any

DECISIONS = ["none", "partial", "full"]


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.1f}%"


def _num(x: float | None, nd: int = 1) -> str:
    return "n/a" if x is None else f"{x:.{nd}f}"


def _signed(x: float | None) -> str:
    return "n/a" if x is None else f"{x:+.1f}"


def render_report(meta: dict, calls: list[dict], records: list[dict], s: dict[str, Any],
                  run_file: str) -> str:
    by_id = {r["id"]: r for r in records}
    ok_calls = [c for c in calls if not c.get("error")]
    lat = [c["latency_ms"] for c in calls if c.get("latency_ms") is not None]
    tok_in = sum(c.get("input_tokens") or 0 for c in ok_calls)
    tok_out = sum(c.get("output_tokens") or 0 for c in ok_calls)
    costs = [c["cost_usd"] for c in ok_calls if c.get("cost_usd") is not None]
    models = sorted({c.get("model") for c in calls if c.get("model")})

    L: list[str] = []
    w = L.append
    w(f"# Evaluation report: `{meta['name']}`")
    w("")
    w("> Generated by `python -m evals.run` from the run file below; "
      "`--replay` reproduces this file exactly.")
    w("")
    w("## Run")
    w("")
    w("| | |")
    w("|---|---|")
    w(f"| Run file | `{run_file}` |")
    w(f"| Started (UTC) | {meta['started_at']} |")
    w(f"| Backend | `{meta['backend']}` |")
    w(f"| Model | {', '.join(f'`{m}`' for m in models) or 'n/a'} |")
    w(f"| Dataset | `{meta['dataset']}` (sha `{meta['dataset_sha']}`) |")
    w(f"| Analyzer | `ai_analyzer.py` sha `{meta['analyzer_sha']}` at commit `{meta['git_commit']}` |")
    truncated = [c for c in ok_calls if c.get("output_tokens") and c.get("max_tokens")
                 and c["output_tokens"] > c["max_tokens"]]
    w(f"| Responses over `max_tokens` | {len(truncated)} (truncated as production would) |")
    w(f"| Tasks × repeats | {s['n_tasks']} × {meta['repeats']} = {s['n_results']} results "
      f"in {len(calls)} calls ({len(calls) - len(ok_calls)} failed) |")
    w("")
    w("**Read with care.**")
    w("")
    w("- Labels in `tasks_v1` were written by a Claude model following `evals/LABELING.md`, "
      "not by a human domain expert, and the scorer is also a Claude model. Shared model "
      "habits can make agreement look better than it is.")
    if meta["backend"] == "cli":
        w("- Backend `cli` runs the production prompt through the Claude Code CLI on a Claude "
          "subscription, with extended thinking disabled as in production. Differences: a "
          "one-line neutral system prompt (production sends none), and `max_tokens` is "
          "emulated by truncating over-long responses proportionally.")
    w("")

    w("## Headline metrics")
    w("")
    w("| Metric | Value | What it means |")
    w("|---|---|---|")
    w(f"| Band accuracy | {_pct(s['band_accuracy'])} | mean score lands in the labelled band (low / mid / high) |")
    w(f"| In labelled range | {_pct(s['in_range_rate'])} | mean score inside the labeller's accepted range |")
    w(f"| Distance to range (MAE) | {_num(s['mae_distance'])} pts | 0 when inside the range |")
    w(f"| Mean signed error | {_signed(s['mean_signed_error'])} pts | + = scores too high, − = too low |")
    w(f"| Spearman ρ | {_num(s['spearman'], 3)} | ranks tasks in the same order as the labels |")
    w(f"| Decision-layer accuracy | {_pct(s['decision_accuracy'])} | none / partial / full matches the label |")
    w(f"| Silent-failure rate | {_pct(s['silent_failure_rate'])} | results that are defaults (score 50) shown as if real |")
    w(f"| Rule-violation rate | {_pct(s['violation_rate'])} | valid results breaking the prompt's own rules |")
    w(f"| Run-to-run SD (mean / max) | {_num(s['stability_mean_sd'])} / {_num(s['stability_max_sd'])} pts | same task, different repeats |")
    if s["tasks_without_valid_result"]:
        w(f"| Tasks with no valid result | {len(s['tasks_without_valid_result'])} | "
          f"{', '.join(s['tasks_without_valid_result'])} |")
    w("")

    w("## By labelled band")
    w("")
    w("| Band | Tasks | Band accuracy | Mean model score | Mean signed error |")
    w("|---|---|---|---|---|")
    for band, b in s["by_band"].items():
        w(f"| {band} | {b['n']} | {_pct(b['band_accuracy'])} | {_num(b['mean_score'])} | "
          f"{_signed(b['mean_signed_error'])} |")
    w("")

    w("## Decision layer (rows = label, columns = model)")
    w("")
    w("| label \\ model | " + " | ".join(DECISIONS) + " |")
    w("|---|" + "---|" * len(DECISIONS))
    for t in DECISIONS:
        w(f"| **{t}** | " + " | ".join(str(s["decision_confusion"][t][p]) for p in DECISIONS) + " |")
    w("")

    w("## Rule violations")
    w("")
    if s["violations_by_rule"]:
        w("| Rule | Results |")
        w("|---|---|")
        for rule, n in s["violations_by_rule"].items():
            w(f"| `{rule}` | {n} |")
    else:
        w("None.")
    w("")

    w("## Does `score_confidence` mean anything?")
    w("")
    w("Distance to the labelled range per result, grouped by the analyzer's own confidence. "
      "If confidence works, `high` should have the smallest distance.")
    w("")
    w("| score_confidence | Results | Mean distance |")
    w("|---|---|---|")
    for conf, b in s["confidence_buckets"].items():
        w(f"| {conf} | {b['n']} | {_num(b['mean_distance'])} |")
    w("")

    w("## Cost and latency")
    w("")
    w(f"- Tokens: {tok_in:,} in / {tok_out:,} out across {len(ok_calls)} successful calls")
    if costs:
        w(f"- API-equivalent cost: ${sum(costs):.4f} total, "
          f"${sum(costs) / max(1, s['n_results'] - round(s['silent_failure_rate'] * s['n_results'])):.5f} per valid result")
    if lat:
        w(f"- Latency per call: mean {mean(lat) / 1000:.1f} s, max {max(lat) / 1000:.1f} s")
    w("")

    w("## Ten worst tasks")
    w("")
    w("| Task | Label range | Model scores | Decision (label → model) | Why the label says so |")
    w("|---|---|---|---|---|")
    ranked = sorted(s["per_task"], key=lambda t: (-(t.get("distance") if t["n_valid"] else 999), t["id"]))
    for t in ranked[:10]:
        rec = by_id[t["id"]]
        lab = rec["label"]
        scores = ", ".join(f"{x:.0f}" for x in t.get("scores", [])) or "no valid result"
        w(f"| `{t['id']}` {rec['name']} | {lab['score_min']}–{lab['score_max']} ({lab['band']}) | "
          f"{scores} | {lab['decision_layer']} → {t.get('decision', 'n/a')} | {lab['rationale']} |")
    w("")

    w("## All tasks")
    w("")
    w("<details><summary>Per-task table</summary>")
    w("")
    w("| Task | Label | Mean | SD | In range | Decision |")
    w("|---|---|---|---|---|---|")
    for t in s["per_task"]:
        lab = t["label"]
        w(f"| `{t['id']}` | {lab['score_min']}–{lab['score_max']} | {_num(t.get('score'))} | "
          f"{_num(t.get('sd'))} | {'yes' if t.get('in_range') else 'no'} | "
          f"{lab['decision_layer']} → {t.get('decision', 'n/a')} |")
    w("")
    w("</details>")
    w("")
    return "\n".join(L)
